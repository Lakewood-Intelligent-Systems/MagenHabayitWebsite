"""Package only public website files for Cloudflare Workers Static Assets, without dependencies."""
from pathlib import Path
from shutil import copy2, rmtree
from zipfile import ZIP_DEFLATED, ZipFile

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'dist' / 'magenhabayit-site.zip'
SITE_DIRECTORY = ROOT / 'dist' / 'site'
PUBLIC_FILES = (
    'index.html', 'donate.html', 'receive-aid.html', 'contract-with-us.html',
    'styles.css', '_headers',
    'robots.txt', 'sitemap.xml', 'assets/home.svg',
    'assets/zelle-qr.png', 'assets/zelle-qr.pdf', 'assets/logo.png', 'assets/isaac-solway.png',
)


def main():
    # Keep source, Git metadata, and internal documentation out of the deployment.
    for filename in PUBLIC_FILES:
        if not (ROOT / filename).is_file():
            raise FileNotFoundError(f'Missing website file: {filename}')
    OUTPUT.parent.mkdir(exist_ok=True)
    # This directory is generated by this script; remove stale public assets.
    if SITE_DIRECTORY.exists():
        rmtree(SITE_DIRECTORY)
    for filename in PUBLIC_FILES:
        destination = SITE_DIRECTORY / filename
        destination.parent.mkdir(parents=True, exist_ok=True)
        copy2(ROOT / filename, destination)
    with ZipFile(OUTPUT, 'w', compression=ZIP_DEFLATED) as archive:
        for filename in PUBLIC_FILES:
            archive.write(ROOT / filename, arcname=filename)
    print(f'Created {OUTPUT} and {SITE_DIRECTORY}')


if __name__ == '__main__':
    main()
